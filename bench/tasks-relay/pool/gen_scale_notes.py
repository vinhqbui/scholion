#!/usr/bin/env python3
"""Build pool/notes-scale.toml: the ten real E4 lessons plus N noise notes.

Noise notes are irrelevant filler so the `notes` arm must read a large NOTES.md while av
can still surface only the anchored lesson. They use paths that are not the ten signal
anchors, so the PreToolUse hook on a task's relevant file is not flooded. Re-run:

    python3 bench/tasks-relay/pool/gen_scale_notes.py
"""
from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
SIGNAL = HERE / "notes.toml"
OUT = HERE / "notes-scale.toml"
NOISE_COUNT = 290

# Paths that exist in tallyho but are not the signal notes' (path, symbol) anchors.
NOISE_ANCHORS: list[tuple[str, str | None]] = [
    ("tallyho/config.py", "load_config"),
    ("tallyho/text.py", "slugify"),
    ("tallyho/cli.py", "main"),
    ("tallyho/errors.py", "ValidationError"),
    ("tallyho/events.py", "emit"),
    ("tallyho/pricing/tax.py", "tax"),
    ("tallyho/pricing/discounts.py", "apply_discount"),
    ("tallyho/report/csv_export.py", "export_csv"),
    ("tallyho/report/table.py", "render_table"),
    ("tallyho/store/memory.py", "MemoryStore"),
    ("tallyho/store/jsonfile.py", "JsonFileStore"),
    ("tallyho/store/scan.py", "scan_keys"),
    ("tallyho/__init__.py", None),
]

# Templates that sound like agent notes but never help the ten relay tasks.
NOISE_KINDS = ("attempt", "decision", "note")
ATTEMPTS = [
    (
        "Tried calling {sym} twice to force a refresh; the second call returned the same "
        "stale handle and nothing updated.",
        "Left a sleep between calls. Still stale. Need a real invalidation path instead.",
    ),
    (
        "Wrapping {sym} in try/except and retrying on every Exception hid the real error and "
        "made the suite hang on the second pass.",
        "Narrow the except or let it raise. Retries belong at the call site that can back off.",
    ),
    (
        "Caching the return of {sym} in a module global broke tests that expected a fresh "
        "value per case.",
        "Keep the cache on the instance, or clear it in fixtures. Do not use a process global.",
    ),
]
DECISIONS = [
    (
        "Log lines from {sym} must use the structured logger, never print(), so operators can "
        "filter by request id.",
        "Agreed in the ops review. print() in library code is a review reject.",
    ),
    (
        "Public helpers around {sym} take keyword-only arguments after *, so call sites stay "
        "readable when we add options.",
        "Positional extras bit us once when a bool was added in the middle.",
    ),
    (
        "Errors from {sym} raise the library's own error type; do not leak raw OSError to "
        "callers.",
        "Wrap and set `__cause__`. Callers match on our type only.",
    ),
]
NOTES = [
    (
        "Remember {sym} is not thread-safe; each worker needs its own instance or an external "
        "lock.",
        "Documented after a flake under pytest-xdist.",
    ),
    (
        "Docs for {sym} live next to the function, not in the README; keep the one-liner there "
        "in sync when behaviour changes.",
        "README is for operators, not API detail.",
    ),
]


def toml_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def emit_note(
    lines: list[str],
    *,
    pair: str,
    kind: str,
    path: str,
    symbol: str | None,
    summary: str,
    body: str,
    noise: bool,
) -> None:
    assert len(summary) <= 200, (pair, len(summary), summary)
    lines.append("[[note]]")
    lines.append(f'pair = "{pair}"')
    lines.append(f'kind = "{kind}"')
    lines.append(f'path = "{path}"')
    if symbol is not None:
        lines.append(f'symbol = "{symbol}"')
    lines.append(f'summary = "{toml_escape(summary)}"')
    lines.append(f'body = "{toml_escape(body)}"')
    if noise:
        lines.append("noise = true")
    lines.append("")


def main() -> None:
    signal = SIGNAL.read_text()
    # Drop the leading comment block; we rewrite a scale-specific header.
    body_start = signal.find("[[note]]")
    if body_start < 0:
        raise SystemExit(f"{SIGNAL}: no [[note]] blocks")
    signal_notes = signal[body_start:].rstrip() + "\n"

    lines: list[str] = [
        "# E4 at scale: the ten real lessons from notes.toml, plus "
        f"{NOISE_COUNT} irrelevant noise",
        "# notes. Noise sets the noise flag for NOTES.md and av records only; it is not",
        "# committed one-by-one to git. Generated by gen_scale_notes.py — re-run that",
        "# script instead of editing the noise blocks by hand.",
        "",
    ]
    lines.append(signal_notes)
    if not signal_notes.endswith("\n\n"):
        lines.append("")

    for i in range(NOISE_COUNT):
        path, symbol = NOISE_ANCHORS[i % len(NOISE_ANCHORS)]
        sym = symbol or path.rsplit("/", 1)[-1]
        kind = NOISE_KINDS[i % len(NOISE_KINDS)]
        if kind == "attempt":
            summary_t, body_t = ATTEMPTS[i % len(ATTEMPTS)]
        elif kind == "decision":
            summary_t, body_t = DECISIONS[i % len(DECISIONS)]
        else:
            summary_t, body_t = NOTES[i % len(NOTES)]
        summary = summary_t.format(sym=sym)
        if len(summary) > 200:
            summary = summary[:197] + "..."
        body = body_t.format(sym=sym)
        emit_note(
            lines,
            pair=f"noise-{i + 1:04d}",
            kind=kind,
            path=path,
            symbol=symbol,
            summary=summary,
            body=body,
            noise=True,
        )

    text = "\n".join(lines)
    if not text.endswith("\n"):
        text += "\n"
    OUT.write_text(text)
    print(
        f"wrote {OUT.relative_to(HERE.parent.parent.parent)} "
        f"(10 signal + {NOISE_COUNT} noise)"
    )


if __name__ == "__main__":
    main()
